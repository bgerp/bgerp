/** Regression checks for the generated preview script and the bundled sanitizer. */
// php hclean/tests/preview.php | node hclean/tests/preview.cjs
const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const path = require('path');
const payload = JSON.parse(fs.readFileSync(0, 'utf8'));
const library = fs.readFileSync(path.join(__dirname, '../jssanitize/html-css-sanitizer-minified.js'), 'utf8');
let checks = 0;
/** Counts an assertion and retains its diagnostic message. */
function check(value, message) { assert.ok(value, message); checks++; }
/** Runs the real generated JavaScript with either cached or deferred library loading. */
function sanitize(script, loaded) {
    let output = '';
    const context = vm.createContext({window: {}, atob: global.atob, qaUnsafe() { throw new Error('Unexpected execution'); }});
    const load = () => vm.runInContext(library, context);
    if (loaded) load();
    context.document = {
        createElement() { return {}; },
        head: {appendChild(script) { delete context.document; load(); context.document = doc; script.onload(); }},
        getElementById(id) {
            assert.strictEqual(id, 'qa-preview');
            return {contentDocument: {open() {}, write(html) { output += html; }, close() {}}};
        }
    };
    const doc = context.document;
    vm.runInContext(script.replace(/^\s*<script>/, '').replace(/<\/script>\s*$/, ''), context, {timeout: 3000});
    return {output, context};
}
for (const loaded of [true, false]) {
    for (const [name, script] of Object.entries(payload.scripts)) {
        const {output, context} = sanitize(script, loaded);
        check(!/<script|<iframe[^>]+(?:src|srcdoc)=|<object|<svg|\bonload=|\bonerror=|\bonclick=|\bsrcset=|javascript:/i.test(output), name + ': active markup removed: ' + output);
        if (payload.images[name]) {
            check(output.includes('src="' + payload.images[name] + '"'), name + ': embedded image preserved');
            check(output.includes('width="40"') && output.includes('height="20"'), name + ': dimensions preserved');
            check(output.includes('Име: Иван Тестов') && output.includes('12,50 EUR &amp; 4'), name + ': text unchanged');
        }
        if (name === 'normal') {
            const original = context.html_sanitize(payload.html[name], url => url)
                .replace(/(<a\s)((.|\s)+?)(<\/a>)/ig, '$1 target="_blank" $2$4');
            check(output === original, 'Ordinary preview exactly matches the previous sanitizer');
        }
        if (name === 'denied') {
            const data = output.match(/data:[^"\s>]*/g) || [];
            check(data.length === 1 && data[0] === payload.images.png, 'Only the allowed img retains data, never links, CSS or other elements');
        }
        if (name === 'whitespace' || name === 'duplicates') check(output.includes(payload.images.png), name + ': valid PNG survives');
        if (name === 'uppercase') check(/src="DATA:IMAGE\/PNG;BASE64,/.test(output), 'Case-insensitive image declaration');
        if (name === 'escaping') check(output.includes('Кирилица') && output.includes('&lt;/script&gt;'), 'Escaping preserves source text');
    }
}
console.log(`Preview: ${checks} checks passed (generated by PHP ${payload.php}).`);
